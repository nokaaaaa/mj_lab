#!/bin/bash
# When every queue has finished: collect the results, copy the artefacts to the
# shared area, and push the summary to GitHub.
#
#   WAIT_FOR_PIDS="123 456" setsid nohup scripts/publish_results.sh \
#       > ~/publish_results.log 2>&1 < /dev/null &
#
# What goes where, by size:
#   policy.onnx   0.9 MB each -> pushed via Git LFS. It is the deployable
#                 artefact, and only the newest run per motion is published.
#   model_*.pt    6.1 MB each, several per run (~340 MB over the queue) -> never
#                 pushed. Only useful for resuming training on this machine.
#   npz/pkl/video -> /opt/mjlab-share only.
# Keeping the .pt files out is what stops the repo growing by a third of a
# gigabyte every time the queue drains.
set -u

REPO="$HOME/unitree_rl_mjlab"
DOCS="$HOME/traffic-officer-humanoid"
SHARE="/opt/mjlab-share"
STATUS="$REPO/logs/queue_status.txt"
WAIT_FOR_PIDS="${WAIT_FOR_PIDS:-}"

note() { echo "[$(date '+%F %T')] [publish] $*" | tee -a "$STATUS"; }

note "armed; waiting on: ${WAIT_FOR_PIDS:-<nothing>}"
for pid in $WAIT_FOR_PIDS; do
  while kill -0 "$pid" 2>/dev/null; do sleep 120; done
  note "pid $pid finished"
done
# And make sure nothing else is still training.
while [ "$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .)" -gt 0 ]; do
  sleep 120
done
note "all training finished"

# --- 1. results table -------------------------------------------------------
note "collecting results"
cd "$REPO" || exit 1
unitree-rl-mjlab scripts/collect_results.py --out "$DOCS/docs/08-results.md" \
  >>"$STATUS.publish" 2>&1 || { note "FAIL collect_results"; exit 1; }

# --- 2. artefacts to the shared area ----------------------------------------
note "copying artefacts to $SHARE"
mkdir -p "$SHARE/logs" "$SHARE/motions/npz" 2>/dev/null
cp -n "$REPO/src/assets/motions/r1/"*.npz "$SHARE/motions/npz/" 2>/dev/null
for run in "$REPO"/logs/rsl_rl/*/*/; do
  [ -f "$run/policy.onnx" ] || continue
  dest="$SHARE/logs/$(basename "$(dirname "$run")")__$(basename "$run")"
  [ -d "$dest" ] && continue
  mkdir -p "$dest"
  cp "$run"/policy.onnx* "$dest/" 2>/dev/null
  cp "$run"/model_*.pt "$dest/" 2>/dev/null
  cp -r "$run"/params "$dest/" 2>/dev/null
done
chgrp -R mjlab "$SHARE" 2>/dev/null; chmod -R g+rwX "$SHARE" 2>/dev/null

# --- 3. deployable policies (LFS) -------------------------------------------
# One directory per motion, holding only the newest run's policy.onnx.
note "staging policies for LFS"
cd "$DOCS" || exit 1
for exp_dir in "$REPO"/logs/rsl_rl/*/; do
  exp=$(basename "$exp_dir")
  for run in $(ls -td "$exp_dir"*/ 2>/dev/null); do
    [ -f "$run/policy.onnx" ] || continue
    base=$(basename "$run")
    # <timestamp>_<clip> -> clip; a bare timestamp -> the experiment name
    motion=$(echo "$base" | sed -E 's/^[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_?//')
    [ -z "$motion" ] && motion="$exp"
    dest="models/$motion"
    # Newest run wins; ls -td put it first, so skip once the directory exists.
    [ -d "$dest" ] && continue
    mkdir -p "$dest"
    cp "$run"/policy.onnx "$dest/" 2>/dev/null
    cp "$run"/policy.onnx.data "$dest/" 2>/dev/null
    printf 'run: %s\nexperiment: %s\n' "$base" "$exp" > "$dest/SOURCE.txt"
  done
done

# --- 4. push ----------------------------------------------------------------
# Refresh the copies of files the queues may have changed.
cp "$REPO/scripts/prepare_motions.sh" "$REPO/scripts/collect_results.py" \
   "$REPO/scripts/train_queue"*.sh "$REPO/scripts/publish_results.sh" \
   files/unitree_rl_mjlab/scripts/ 2>/dev/null
cp "$REPO/src/tasks/velocity/config/r1/stairs_env_cfgs.py" \
   files/unitree_rl_mjlab/src/tasks/velocity/config/r1/ 2>/dev/null
( cd "$REPO" && git diff -- scripts/csv_to_npz.py simulate/config.yaml \
    src/assets/robots/unitree_r1/xmls/r1.xml deploy/robots/r1/ \
    src/tasks/velocity/config/r1/__init__.py ) > patches/unitree_rl_mjlab.patch 2>/dev/null

if git diff --quiet && git diff --cached --quiet && [ -z "$(git status --porcelain)" ]; then
  note "nothing to push"
  exit 0
fi

git add -A
git commit -q -F - <<EOF
Results from the queued training runs

Generated by scripts/collect_results.py from the tensorboard events, so the
numbers are whatever the runs actually ended at rather than anything retyped by
hand. Weights and motion data are not in here - they go to /opt/mjlab-share.

Run on $(date '+%Y-%m-%d %H:%M') after the training queues drained.

Co-Authored-By: Claude Opus 5 (1M context) <noreply@anthropic.com>
Claude-Session: https://claude.ai/code/session_01GFHmwkkYzYAzB6K8nT5dEP
EOF

if git push -q origin main 2>>"$STATUS.publish"; then
  note "pushed to origin/main"
else
  note "push failed - trying to rebase onto whatever landed meanwhile"
  if git pull --rebase -q origin main 2>>"$STATUS.publish" && git push -q origin main 2>>"$STATUS.publish"; then
    note "pushed after rebase"
  else
    note "FAIL push - the commit is local, resolve by hand in $DOCS"
    exit 1
  fi
fi

# Keep the read-only clone the other account uses in step with it.
sudo -n git -C "$SHARE/docs/traffic-officer-humanoid" pull -q origin main 2>/dev/null \
  && sudo -n chmod -R g+rwX "$SHARE/docs" 2>/dev/null \
  && note "shared clone synced" \
  || note "shared clone not synced (needs sudo); run: sudo git -C $SHARE/docs/traffic-officer-humanoid pull"

note "publish finished"
